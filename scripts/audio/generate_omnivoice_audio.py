"""
Render every narration clip with OmniVoice (https://huggingface.co/k2-fsa/OmniVoice).

1. Export the scripts:   npm run audio:scripts
2. Render the audio:     <omnivoice-venv>/Scripts/python scripts/audio/generate_omnivoice_audio.py

One narrator voice per language is designed once (saved under
assets/audio/narration/voices/) and then cloned for every clip, so the whole site
speaks with the same voice. Clips whose text has not changed are skipped, so
re-running only renders new or edited text.

Outputs
  assets/audio/narration/<lang>/<clip-id>.mp3   loudness-normalised mono MP3
  assets/audio/narration/cache.json             text hash + duration per clip
  src/data/narrationManifest.js                 what the site loads

Options
  --only PREFIX        render only clip ids starting with PREFIX (e.g. ch1-, quiz-)
  --lang mal|eng       render one language
  --force              re-render even if the text is unchanged
  --redesign-voices    design new narrator voices (then re-renders everything)
  --num-step N         diffusion steps (32 = best quality, 16 = faster)
  --seed N             seed used when designing voices
  --manifest-only      rebuild the manifest from existing files without rendering

Requires: scripts/audio/requirements.txt (omnivoice, torch with CUDA, soundfile)
and ffmpeg on PATH.
The OmniVoice model weights are licensed CC-BY-NC (non-commercial use).
"""

import argparse
import json
import os
import subprocess
import sys
import tempfile
import time

ROOT = os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
NARRATION_DIR = os.path.join(ROOT, 'assets', 'audio', 'narration')
SCRIPTS_FILE = os.path.join(NARRATION_DIR, 'scripts.json')
CACHE_FILE = os.path.join(NARRATION_DIR, 'cache.json')
VOICES_DIR = os.path.join(NARRATION_DIR, 'voices')
MANIFEST_FILE = os.path.join(ROOT, 'src', 'data', 'narrationManifest.js')
SAMPLE_RATE = 24000

# One warm, gentle storyteller per language. The reference sentence is rendered
# once with voice design, then used as the voice-clone prompt for every clip.
VOICES = {
    'mal': {
        'language_id': 'ml',
        'instruct': 'female, young adult, moderate pitch',
        'ref_text': 'കുഞ്ഞുങ്ങളേ, ഇന്ന് നമുക്ക് ഈശോയുടെ സ്നേഹത്തെക്കുറിച്ച് മനോഹരമായ ഒരു കഥ കേൾക്കാം.',
    },
    'eng': {
        'language_id': 'en',
        'instruct': 'female, young adult, moderate pitch',
        'ref_text': 'Hello, little friends! Today we will listen to a beautiful story about the love of Jesus.',
    },
}


def load_json(path, default):
    if os.path.exists(path):
        with open(path, encoding='utf-8') as f:
            return json.load(f)
    return default


def save_json(path, data):
    with open(path, 'w', encoding='utf-8', newline='\n') as f:
        json.dump(data, f, ensure_ascii=False, indent=2, sort_keys=True)
        f.write('\n')


def clip_path(lang, clip_id):
    return os.path.join(NARRATION_DIR, lang, f'{clip_id}.mp3')


def encode_mp3(samples, out_path):
    """Write a temp WAV, then loudness-normalise and encode a small mono MP3."""
    import soundfile as sf
    os.makedirs(os.path.dirname(out_path), exist_ok=True)
    fd, wav_path = tempfile.mkstemp(suffix='.wav')
    os.close(fd)
    try:
        sf.write(wav_path, samples, SAMPLE_RATE)
        subprocess.run([
            'ffmpeg', '-y', '-loglevel', 'error', '-i', wav_path,
            '-af', 'highpass=f=60,loudnorm=I=-18:TP=-1.5:LRA=11',
            '-ar', str(SAMPLE_RATE), '-ac', '1',
            '-c:a', 'libmp3lame', '-b:a', '48k', out_path
        ], check=True)
    finally:
        os.remove(wav_path)


def probe_seconds(path):
    out = subprocess.run(
        ['ffprobe', '-v', 'error', '-show_entries', 'format=duration', '-of', 'csv=p=0', path],
        capture_output=True, text=True, check=True
    ).stdout.strip()
    return round(float(out), 2)


def write_manifest(clips, cache):
    """Manifest of clips that exist on disk: id -> lang -> { src, seconds }."""
    manifest = {}
    for clip in clips:
        path = clip_path(clip['lang'], clip['id'])
        entry = cache.get(f"{clip['lang']}/{clip['id']}")
        if not os.path.exists(path) or not entry or entry.get('hash') != clip['hash']:
            continue
        rel = os.path.relpath(path, ROOT).replace(os.sep, '/')
        manifest.setdefault(clip['id'], {})[clip['lang']] = {
            'src': f"{rel}?v={clip['hash']}",
            'seconds': entry.get('seconds', 0),
        }
    body = json.dumps(manifest, ensure_ascii=False, indent=2, sort_keys=True)
    with open(MANIFEST_FILE, 'w', encoding='utf-8', newline='\n') as f:
        f.write('/**\n * Generated by scripts/audio/generate_omnivoice_audio.py - do not edit by hand.\n'
                ' * Narration clips rendered with OmniVoice: clip id -> language -> { src, seconds }.\n */\n')
        f.write(f'export const NARRATION_MANIFEST = {body};\n')
    total = sum(len(v) for v in manifest.values())
    print(f'Manifest: {total} clips across {len(manifest)} ids -> {os.path.relpath(MANIFEST_FILE, ROOT)}')


def check_clip(clip, seconds):
    """Flag clips whose length is implausible for their text (truncated or runaway)."""
    chars = len(clip['text'])
    rate = chars / max(seconds, 0.1)
    low, high = (4, 30) if clip['lang'] == 'mal' else (6, 28)
    if rate < low or rate > high:
        return f'suspicious length: {seconds}s for {chars} chars ({rate:.1f} chars/s)'
    return None


def main():
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument('--only', default='')
    parser.add_argument('--lang', choices=['mal', 'eng'])
    parser.add_argument('--force', action='store_true')
    parser.add_argument('--redesign-voices', action='store_true')
    parser.add_argument('--num-step', type=int, default=32)
    parser.add_argument('--seed', type=int, default=7)
    parser.add_argument('--manifest-only', action='store_true')
    args = parser.parse_args()

    clips = load_json(SCRIPTS_FILE, None)
    if clips is None:
        sys.exit('scripts.json not found - run: npm run audio:scripts')
    cache = load_json(CACHE_FILE, {})

    if args.manifest_only:
        write_manifest(clips, cache)
        return

    todo = [
        c for c in clips
        if c['id'].startswith(args.only) and (not args.lang or c['lang'] == args.lang)
        and (args.force or args.redesign_voices
             or cache.get(f"{c['lang']}/{c['id']}", {}).get('hash') != c['hash']
             or not os.path.exists(clip_path(c['lang'], c['id'])))
    ]
    print(f'{len(clips)} clips in scripts.json; {len(todo)} to render.')
    if not todo and not args.redesign_voices:
        write_manifest(clips, cache)
        return

    import numpy as np
    import soundfile as sf
    import torch
    from omnivoice import OmniVoice

    device = 'cuda:0' if torch.cuda.is_available() else 'cpu'
    print(f'Loading OmniVoice on {device} ...')
    model = OmniVoice.from_pretrained(
        'k2-fsa/OmniVoice', device_map=device,
        dtype=torch.float16 if device.startswith('cuda') else torch.float32
    )

    # Narrator voices: design once, then reuse as the clone prompt.
    os.makedirs(VOICES_DIR, exist_ok=True)
    for lang, voice in VOICES.items():
        ref_path = os.path.join(VOICES_DIR, f'{lang}-narrator.wav')
        if os.path.exists(ref_path) and not args.redesign_voices:
            continue
        torch.manual_seed(args.seed)
        print(f'Designing the {lang} narrator voice ({voice["instruct"]}) ...')
        audio = model.generate(text=voice['ref_text'], instruct=voice['instruct'],
                               language_id=voice['language_id'], num_step=args.num_step)
        sf.write(ref_path, audio[0], SAMPLE_RATE)
        print(f'  saved {os.path.relpath(ref_path, ROOT)} ({len(audio[0]) / SAMPLE_RATE:.1f}s)')

    warnings = []
    started = time.time()
    audio_seconds = 0.0
    for i, clip in enumerate(todo, 1):
        voice = VOICES[clip['lang']]
        ref_path = os.path.join(VOICES_DIR, f"{clip['lang']}-narrator.wav")
        t0 = time.time()
        audio = model.generate(
            text=clip['text'], ref_audio=ref_path, ref_text=voice['ref_text'],
            language_id=voice['language_id'], num_step=args.num_step,
        )
        samples = np.asarray(audio[0], dtype=np.float32)
        out = clip_path(clip['lang'], clip['id'])
        encode_mp3(samples, out)
        seconds = probe_seconds(out)
        audio_seconds += seconds
        cache[f"{clip['lang']}/{clip['id']}"] = {'hash': clip['hash'], 'seconds': seconds}
        problem = check_clip(clip, seconds)
        if problem:
            warnings.append(f"{clip['lang']}/{clip['id']}: {problem}")
        print(f"[{i}/{len(todo)}] {clip['lang']}/{clip['id']}  {seconds:.1f}s audio in {time.time() - t0:.1f}s"
              + (f'  WARNING {problem}' if problem else ''))
        if i % 10 == 0:
            save_json(CACHE_FILE, cache)

    save_json(CACHE_FILE, cache)
    write_manifest(clips, cache)
    elapsed = time.time() - started
    print(f'Rendered {len(todo)} clips: {audio_seconds / 60:.1f} min of audio in {elapsed / 60:.1f} min.')
    if warnings:
        print(f'{len(warnings)} clip(s) to listen to:')
        for w in warnings:
            print('  ' + w)


if __name__ == '__main__':
    main()
